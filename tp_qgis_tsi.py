    def start_picking(self, tool):
        self.dlg.hide()
        self.canvas.setMapTool(tool)


    def point_transform_to_4326(self,point):
        src = self.canvas.mapSettings().destinationCrs()
        dst = QgsCoordinateReferenceSystem("EPSG:4326")
        tr = QgsCoordinateTransform(src, dst, QgsProject.instance())
        p = tr.transform(point)
        return p

    def button_map(self,point):
        self.get_coordinates(point)
        self.get_adress(point)

    def button_map_objs(self, point):
            self.get_objects(point)
            self.draw_buffer(point)
            self.canvas.unsetMapTool(self.pointTool_objs)
            self.dlg.show()


    def get_coordinates(self, point):
        p = self.point_transform_to_4326(point)

        self.dlg.doubleSpinBox_latitude.setValue(p.y())
        self.dlg.doubleSpinBox_longitude.setValue(p.x())

        self.canvas.unsetMapTool(self.pointTool)
        self.dlg.show()

    def get_adress(self,point):
        p = self.point_transform_to_4326(point)
        try:
            r = requests.get(
                "https://data.geopf.fr/geocodage/reverse",
                params={
                    "lon": p.x(),
                    "lat": p.y(),
                    "index": "address",
                    "type": "housenumber",
                    "limit": 1,
                },
                timeout=5,
            )
            r.raise_for_status()
            data = r.json()

        except (requests.RequestException, ValueError):
            self.iface.messageBar().pushWarning("BAN", "Service BAN injoignable")
            return

        salacted_data = data["features"][0]["properties"]
        type_voie, nom_voie = self.split_street(salacted_data.get("street", ""))

        labels = {
            self.dlg.label_numero_voie: salacted_data.get("housenumber", ""),
            self.dlg.label_type_voie: type_voie,
            self.dlg.label_nom_voie: nom_voie,
            self.dlg.label_insee: salacted_data.get("citycode", ""),
            self.dlg.label_commune: salacted_data.get("city", ""),
            self.dlg.label_adresse: salacted_data.get("label", ""),
        }
        for label, text in labels.items():
            label.setText(text)
            label.adjustSize()

    def split_street(self, street):
        parts = street.split(" ", 1)
        if len(parts) == 2 and parts[0].lower() in TYPES_VOIE:
            return parts[0], parts[1]
        return "", street

    def get_objects(self,point):
        selected_layer = self.dlg.mMapLayerComboBox.currentLayer()
        distance = self.dlg.spinBox_distance.value()
        if selected_layer is None:
            self.iface.messageBar().pushWarning("Comptage", "Aucune couche sélectionnée")
            return

        # CRS du canvas -> CRS de la couche
        tr = QgsCoordinateTransform(
            self.canvas.mapSettings().destinationCrs(),
            selected_layer.crs(),
            QgsProject.instance())
        p = tr.transform(point)

        d = QgsDistanceArea()
        d.setSourceCrs(selected_layer.crs(), QgsProject.instance().transformContext())
        d.setEllipsoid("WGS84")

        count = 0
        for feature in selected_layer.getFeatures():
            geom = feature.geometry()
            if geom.isNull():
                continue
            if d.measureLine(p, geom.centroid().asPoint()) <= distance:
                count += 1

        self.dlg.label_objs.setText(str(count))
        self.dlg.label_distance.setText(str(distance))
        self.dlg.label_objs.adjustSize()
        self.dlg.label_distance.adjustSize()

    def get_buffer_layer(self):
        layer = getattr(self, "buffer_layer", None)
        # la couche a pu être supprimée du projet par l'utilisateur
        if layer is None or QgsProject.instance().mapLayer(self.buffer_layer_id) is None:
            layer = QgsVectorLayer("Polygon?crs=EPSG:4326", "Zone tampon", "memory")

            symbol = QgsFillSymbol.createSimple({
                "color": "0,0,0,0",
                "style": "no",
                "outline_color": "#000000",
                "outline_width": "0.3",
                "outline_style": "solid",
            })
            layer.renderer().setSymbol(symbol)

            QgsProject.instance().addMapLayer(layer)
            self.buffer_layer = layer
            self.buffer_layer_id = layer.id()
        return layer

    def draw_buffer(self, point):

        distance = self.dlg.spinBox_distance.value()

        p = self.point_transform_to_4326(point)

        proj = (f"+proj=aeqd +lat_0={p.y()} +lon_0={p.x()} "
                "+x_0=0 +y_0=0 +datum=WGS84 +units=m +no_defs")
        aeqd = QgsCoordinateReferenceSystem.fromProj(proj)
        wgs84 = QgsCoordinateReferenceSystem("EPSG:4326")
        ctx = QgsProject.instance().transformContext()

        # cercle de rayon X mètres autour de (0, 0), puis retour en WGS84
        geom = QgsGeometry.fromPointXY(QgsPointXY(0, 0)).buffer(distance, 64)
        geom.transform(QgsCoordinateTransform(aeqd, wgs84, ctx))

        layer = self.get_buffer_layer()

        # RG2 : on supprime les anciennes zones avant d'ajouter la nouvelle
        layer.dataProvider().truncate()

        feat = QgsFeature()
        feat.setGeometry(geom)
        layer.dataProvider().addFeatures([feat])
        layer.updateExtents()
        layer.triggerRepaint()